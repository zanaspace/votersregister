// Now, synchronize every politician's polling unit into data/voter_records.json, data/voter_records.csv, and data/voter_records.jsonl
const voterRecordsJsonPath = 'data/voter_records.json';
const voterRecordsCsvPath = 'data/voter_records.csv';
const voterRecordsJsonlPath = 'data/voter_records.jsonl';

const voterRecords = JSON.parse(fs.readFileSync(voterRecordsJsonPath, 'utf8'));
const recordMap = new Map();
for (const r of voterRecords) {
  recordMap.set(r.pu_code, r);
}

let addedCount = 0;
let updatedCount = 0;

for (const p of VERIFIED_POLITICIANS) {
  const existing = recordMap.get(p.pu_code);
  if (existing) {
    // Ensure exact official Ward and PU name match
    existing.ward = p.ward;
    existing.pu_name = p.pu_name;
    existing.state = p.state;
    existing.lga = p.lga;
    existing.count_2023 = p.count_2023;
    existing.count_2027 = p.count_2027;
    existing.difference = p.difference;
    updatedCount++;
  } else {
    // Add new official record
    const newRecord = {
      pu_code: p.pu_code,
      state: p.state,
      lga: p.lga,
      ward: p.ward,
      pu_name: p.pu_name,
      count_2023: p.count_2023,
      count_2027: p.count_2027,
      difference: p.difference,
      status: "added",
      recorded_at: new Date().toISOString()
    };
    recordMap.set(p.pu_code, newRecord);
    voterRecords.push(newRecord);
    addedCount++;
  }
}

console.log(`Voter records synced: ${addedCount} added, ${updatedCount} updated. Total records now: ${voterRecords.length}`);

